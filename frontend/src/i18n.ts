const DICTS: Record<Lang, Dict> = { en, hi, mr, ta };
const LOCALES: Record<Lang, string> = { en: "en-IN", hi: "hi-IN", mr: "mr-IN", ta: "ta-IN" };

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

/** Translate `key` into `lang`, falling back to English, then to the key itself. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const s = DICTS[lang]?.[key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : s;
}

export function localeFor(lang: Lang): string {
  return LOCALES[lang] ?? "en-IN";
}

export function useT(): { t: TFn; lang: Lang } {
  const { lang } = useAuth();
  const t = useCallback<TFn>((key, vars) => translate(lang, key, vars), [lang]);
  return { t, lang };
}
